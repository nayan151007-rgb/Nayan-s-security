interface ScanFormProps {
  isScanning: boolean;
  onSubmitScan: (payload: {
    targetModel: TargetModel;
    promptText: string;
    responseText: string;
    scanCategories: TrustCategory[];
  }) => Promise<void>;
}

export function ScanForm({ isScanning, onSubmitScan }: ScanFormProps) {
  const [targetModel, setTargetModel] = useState<TargetModel>('gemini-2.5-flash');
  const [promptText, setPromptText] = useState<string>(SCAN_PRESETS[0].promptText);
  const [responseText, setResponseText] = useState<string>(
    SCAN_PRESETS[0].responseText
  );
  const [scanCategories, setScanCategories] = useState<TrustCategory[]>([
    'Prompt Security',
    'Data Privacy',
    'Safety & Toxicity',
    'Reliability',
  ]);
  const [validationError, setValidationError] = useState<string | null>(null);

  const toggleCategory = (category: TrustCategory) => {
    setValidationError(null);
    setScanCategories((prev) =>
      prev.includes(category)
        ? prev.filter((item) => item !== category)
        : [...prev, category]
    );
  };

  const applyPreset = (preset: ScanPreset) => {
    setValidationError(null);
    setTargetModel(preset.targetModel);
    setPromptText(preset.promptText);
    setResponseText(preset.responseText);
    setScanCategories(preset.scanCategories);
  };

  const handleReset = () => {
    setValidationError(null);
    setPromptText('');
    setResponseText('');
    setScanCategories([
      'Prompt Security',
      'Data Privacy',
      'Safety & Toxicity',
      'Reliability',
    ]);
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setValidationError(null);

    const parsed = scanSchema.safeParse({
      targetModel,
      promptText,
      responseText,
      scanCategories,
    });

    if (!parsed.success) {
      setValidationError(
        parsed.error.issues[0]?.message || 'Please check scan input fields.'
      );
      return;
    }

    await onSubmitScan({
      targetModel: parsed.data.targetModel,
      promptText: parsed.data.promptText,
      responseText: parsed.data.responseText || '',
      scanCategories: parsed.data.scanCategories,
    });
  };

  return (
    <form
      onSubmit={handleSubmit}
      className="bg-white border border-slate-200 rounded-xl divide-y divide-slate-200"
    >
      {/* Preset Scenario Selector */}
      <div className="p-5 sm:p-6">
        <div className="flex flex-wrap items-center justify-between gap-2 mb-3">
          <h2 className="text-base font-semibold text-slate-900">
            Prompt &amp; Response Evaluation Input
          </h2>
          <span className="text-xs text-slate-500">
            Load red-team test vector:
          </span>
        </div>

        <div className="flex flex-wrap gap-1.5">
          {SCAN_PRESETS.map((preset) => (
            <button
              key={preset.id}
              type="button"
              disabled={isScanning}
              onClick={() => applyPreset(preset)}
              className="px-2.5 py-1.5 text-xs font-medium text-slate-700 bg-slate-100 hover:bg-slate-200/80 rounded-md transition-colors whitespace-nowrap shrink-0 disabled:opacity-50"
            >
              {preset.label}
            </button>
          ))}
        </div>
      </div>

      {/* Main Form Controls */}
      <div className="p-5 sm:p-6 space-y-5">
        <div>
          <label
            htmlFor="target-model"
            className="block text-xs font-semibold text-slate-700 mb-1.5"
          >
            Target Gemini Evaluation Model
          </label>
          <select
            id="target-model"
            value={targetModel}
            disabled={isScanning}
            onChange={(e) => setTargetModel(e.target.value as TargetModel)}
            className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-lg text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-600 focus:border-blue-600"
          >
            {TARGET_MODELS.map((model) => (
              <option key={model} value={model}>
                {model === 'gemini-2.5-flash'
                  ? 'gemini-2.5-flash (Low-Latency Red-Team Audit)'
                  : model === 'gemini-2.5-pro'
                    ? 'gemini-2.5-pro (Deep Policy & Reasoning Audit)'
                    : 'gemini-3.8-flash (Next-Gen High-Speed Inspector)'}
              </option>
            ))}
          </select>
        </div>

        <div>
          <div className="flex items-center justify-between mb-1.5">
            <label
              htmlFor="prompt-text"
              className="text-xs font-semibold text-slate-700"
            >
              Input Prompt Payload <span className="text-red-600">*</span>
            </label>
            <span className="text-xs font-mono tabular-nums text-slate-500">
              {promptText.length.toLocaleString()} / 5,000
            </span>
          </div>
          <textarea
            id="prompt-text"
            rows={5}
            maxLength={5000}
            disabled={isScanning}
            value={promptText}
            onChange={(e) => {
              setValidationError(null);
              setPromptText(e.target.value);
            }}
            placeholder="Paste user prompt, RAG context block, or system instruction template to inspect for prompt injection, PII exposure, or policy violations..."
            className="w-full px-3.5 py-2.5 text-sm font-mono bg-slate-50/60 border border-slate-300 rounded-lg text-slate-900 placeholder:text-slate-400 focus:bg-white focus:outline-none focus:ring-2 focus:ring-blue-600 focus:border-blue-600 leading-relaxed"
          />
        </div>

        <div>
          <div className="flex items-center justify-between mb-1.5">
            <label
              htmlFor="response-text"
              className="text-xs font-semibold text-slate-700"
            >
              Model Response Output{' '}
              <span className="font-normal text-slate-500">(Optional)</span>
            </label>
            <span className="text-xs font-mono tabular-nums text-slate-500">
              {responseText.length.toLocaleString()} / 10,000
            </span>
          </div>
          <textarea
            id="response-text"
            rows={4}
            maxLength={10000}
            disabled={isScanning}
            value={responseText}
            onChange={(e) => {
              setValidationError(null);
              setResponseText(e.target.value);
            }}
            placeholder="Optionally paste the generated LLM completion to inspect for data leakage, toxicity, ungrounded hallucinations, or missing human-oversight disclosures..."
            className="w-full px-3.5 py-2.5 text-sm font-mono bg-slate-50/60 border border-slate-300 rounded-lg text-slate-900 placeholder:text-slate-400 focus:bg-white focus:outline-none focus:ring-2 focus:ring-blue-600 focus:border-blue-600 leading-relaxed"
          />
        </div>

        <div>
          <span className="block text-xs font-semibold text-slate-700 mb-2">
            Active AI Trust &amp; Safety Domains
          </span>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
            {TRUST_CATEGORIES.map((category) => {
              const checked = scanCategories.includes(category);
              return (
                <label
                  key={category}
                  className={`flex items-center gap-2.5 px-3 py-2 rounded-lg border text-xs font-medium cursor-pointer transition-colors ${
                    checked
                      ? 'border-blue-600 bg-blue-50/60 text-slate-900'
                      : 'border-slate-200 bg-white text-slate-600 hover:bg-slate-50'
                  }`}
                >
                  <input
                    type="checkbox"
                    checked={checked}
                    disabled={isScanning}
                    onChange={() => toggleCategory(category)}
                    className="rounded border-slate-300 text-blue-600 focus:ring-blue-600"
                  />
                  <span className="truncate">{category}</span>
                </label>
              );
            })}
          </div>
        </div>

        {validationError && (
          <p role="alert" className="text-xs font-medium text-red-600">
            {validationError}
          </p>
        )}
      </div>

      {/* Action Bar */}
      <div className="px-5 py-4 sm:px-6 bg-slate-50/70 rounded-b-xl flex items-center justify-between gap-3">
        <button
          type="button"
          onClick={handleReset}
          disabled={isScanning}
          className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium text-slate-700 hover:text-slate-900 bg-white border border-slate-300 rounded-lg transition-colors whitespace-nowrap shrink-0 disabled:opacity-50"
        >
          <RotateCcw className="w-3.5 h-3.5" />
          <span>Clear Fields</span>
        </button>

        <button
          type="submit"
          disabled={isScanning}
          className="inline-flex items-center gap-2 px-5 py-2.5 text-xs font-semibold text-white bg-blue-600 hover:bg-blue-700 rounded-lg transition-colors whitespace-nowrap shrink-0 disabled:opacity-60"
        >
          {isScanning ? (
            <>
              <Loader2 className="w-4 h-4 animate-spin" />
              <span>Evaluating with Gemini...</span>
            </>
          ) : (
            <>
              <Play className="w-3.5 h-3.5 fill-current" />
              <span>Run Security Audit</span>
            </>
          )}
        </button>
      </div>
    </form>
  );
}
